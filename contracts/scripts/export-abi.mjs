// Writes the contract ABIs into the web app as typed `as const` exports.
import { readFileSync, writeFileSync } from "node:fs";

const out = ["// Generated by contracts/scripts/export-abi.mjs. Do not edit.", ""];
for (const name of ["Kleos", "KleosUSD"]) {
  const { abi } = JSON.parse(readFileSync(`artifacts/src/${name}.sol/${name}.json`, "utf8"));
  out.push(`export const ${name === "Kleos" ? "kleos" : "kleosUsd"}Abi = ${JSON.stringify(abi, null, 2)} as const;`, "");
}
writeFileSync("../web/src/lib/abi.ts", out.join("\n"));
console.log("wrote web/src/lib/abi.ts");
